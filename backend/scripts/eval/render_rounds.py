def table(rows: list[dict]) -> str:
    out = ["| 用例 | 任务类型 | 准确性/25 | 相关性/25 | 完整性/25 | 格式/25 | 总分 | 结论 |",
           "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        flag = "PASS" if r["passed"] else "**FAIL**"
        if r["redlines"]:
            flag += "（红线）"
        out.append(
            f"| {r['id']} | {r['mmtu_task']} | {r['accuracy']} | {r['relevance']} | "
            f"{r['completeness']} | {r['format']} | **{r['total']}** | {flag} |"
        )
    return "\n".join(out)


def main() -> int:
    # 只渲染命令行指定的轮次，避免重复追加已写入的章节
    wanted = [int(a) for a in sys.argv[1:]] or sorted(NOTES)
    chunks: list[str] = []
    for rn in wanted:
        path = RESULTS / f"round_{rn}.json"
        if not path.exists():
            print(f"跳过第 {rn} 轮（无结果文件）")
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        note = NOTES[rn]
        chunks.append(f"""---

## {note['title']}

- 用例 {data['case_count']} 条 | 达标 {data['passed_count']} | 未达标 {data['failed_count']}
- **平均分 {data['avg_total']}**（准确性 {data['avg_accuracy']} / 相关性 {data['avg_relevance']} / 完整性 {data['avg_completeness']} / 格式 {data['avg_format']}）
- 结果文件：`docs/eval/results/round_{rn}.json`

> {note['meta']}

### {rn}.1 逐项得分

{table(data['rows'])}

### {rn}.2 问题诊断

{note['diag']}

### {rn}.3 本轮改动

{note['changes']}
""")
    target = ROOT / "docs" / "eval" / "AI_LAB_EVAL_ROUNDS.md"
    with target.open("a", encoding="utf-8") as fh:
        fh.write("\n" + "\n".join(chunks))
    print(f"已追加 {len(chunks)} 轮记录到 {target}")
    return 0


